def expand(pattern: str) -> list[Path]:
    """Expand brace alternatives and globs relative to results/."""
    import glob
    import itertools
    import re

    parts = re.split(r"(\{[^{}]*\})", pattern)
    options = []
    for part in parts:
        if part.startswith("{") and part.endswith("}"):
            body = part[1:-1]
            m = re.fullmatch(r"(\d+)\.\.(\d+)", body)
            options.append([str(i) for i in range(int(m.group(1)), int(m.group(2)) + 1)] if m else body.split(","))
        else:
            options.append([part])
    paths: list[Path] = []
    for combo in itertools.product(*options):
        candidate = "".join(combo)
        paths.extend(Path(p) for p in glob.glob(str(RESULTS / candidate)))
    return sorted(set(paths))


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    lines = ["# Artifact inventory", "", "Generated by `harness/build_artifact_inventory.py`. Paths are relative to `results/`.", ""]
    for table, patterns in TABLES.items():
        lines += [f"## {table}", "", "| artifact | bytes | sha256 |", "|---|---:|---|"]
        seen = 0
        for pattern in patterns:
            for path in expand(pattern):
                if path.is_file():
                    rel = path.resolve().relative_to(RESULTS.resolve()) if RESULTS.resolve() in path.resolve().parents else path.resolve().relative_to(ROOT.resolve())
                    lines.append(f"| `{rel}` | {path.stat().st_size} | `{sha256(path)[:16]}…` |")
                    seen += 1
        if seen == 0:
            lines.append("| _(no artifacts yet)_ | | |")
        lines.append("")
    (ROOT / "context" / "ARTIFACT_INVENTORY.md").write_text("\n".join(lines) + "\n")
    print("wrote context/ARTIFACT_INVENTORY.md")


if __name__ == "__main__":
    main()
